/// Paketteki tek bir çeşit.
class SolCesit {
  final String id;
  final List<String> title;
  final List<String> tagline;
  final SolitaireRules rules;
  final GameConfig config;
  const SolCesit(this.id, this.title, this.tagline, this.rules, this.config);
}

List<String> _join(List<String> base, List<List<String>> parts) => [
      for (var i = 0; i < 33; i++) [base[i], for (final p in parts) p[i]].join(' · '),
    ];

List<SolCesit> _build() {
  final out = <SolCesit>[];
  for (final f in _families) {
    for (final combo in f.combos) {
      final keys = combo.split('+');
      final mods = [for (final k in keys) _mods[k]!];
      final id = 'oyun-sol-cesit-${f.key}-${keys.join('-').toLowerCase()}';
      TableauVariant variant(int d) {
        var v = f.base(d);
        for (final m in mods) {
          v = m.apply(v);
        }
        return v;
      }

      final rules = SolitaireRules(gameId: id, variantFor: variant, nodeCap: f.nodeCap, levels: 10000);
      final title = _join(f.title, [for (final m in mods) m.label]);
      final info = [
        for (var i = 0; i < 33; i++) [for (final m in mods) m.expl[i]].join(' '),
      ];
      final config = GameConfig(
        gameId: id,
        title: title,
        tagline: f.tagline,
        seedColor: f.color,
        icon: f.icon,
        rules: rules,
        buildPlay: (ctx) => SolitaireView(ctx: ctx),
        tutorial: [
          TutorialStep(Icons.tune, info),
          TutorialStep(Icons.style, f.rule),
          kSolitaireHowTo,
        ],
      );
      out.add(SolCesit(id, title, f.tagline, rules, config));
    }
  }
  return out;
}

